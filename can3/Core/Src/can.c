typedef struct {
    uint16_t angle;        // 0~8191
    int16_t  speed_rpm;    // rpm
    int16_t  current;      // 实际转矩电流
    uint8_t  error_code;   // 0=正常
    uint32_t last_tick;    // 掉线检测
} C610_Feedback_t;

C610_Feedback_t g_c610[8];   // ID 1~8 → 下标 1~7（下标 0 不用）

void HAL_CAN_RxFifo0MsgPendingCallback(CAN_HandleTypeDef *hcan)
{
    CAN_RxHeaderTypeDef rx_header;
    uint8_t rx_data[8];

    if (HAL_CAN_GetRxMessage(hcan, CAN_RX_FIFO0, &rx_header, rx_data) != HAL_OK)
    {
        Error_Handler();
    }

    /* 只处理标准数据帧 */
    if (rx_header.IDE != CAN_ID_STD || rx_header.RTR != CAN_RTR_DATA)
        return;

    uint32_t id = rx_header.StdId;

    /* C610 反馈：0x201 ~ 0x208 */
    if (id >= 0x201 && id <= 0x208 && rx_header.DLC == 8)
    {
        uint8_t idx = id - 0x200;   // 1~8

        /* 大端解析 */
        g_c610[idx].angle      = (uint16_t)((rx_data[0] << 8) | rx_data[1]);
        g_c610[idx].speed_rpm  = (int16_t )((rx_data[2] << 8) | rx_data[3]);
        g_c610[idx].current    = (int16_t )((rx_data[4] << 8) | rx_data[5]);
        g_c610[idx].error_code = rx_data[7];
        g_c610[idx].last_tick  = HAL_GetTick();

        HAL_GPIO_TogglePin(GPIOH, GPIO_PIN_12);   // 收到反馈闪灯
    }
}
